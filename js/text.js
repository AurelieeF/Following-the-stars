let lang = 'fr';
try { lang = localStorage.getItem('lang') || (navigator.language?.startsWith('fr') ? 'fr' : 'en'); } catch { /* storage blocked */ }
export const getLang = () => lang;
export function setLang(l) { lang = l; document.documentElement.lang = l; try { localStorage.setItem('lang', l); } catch { /* ignore */ } }
document.documentElement.lang = lang;

/** 11.5 → "11,5" in French, "11.5" in English */
export const num = (v) => v.toLocaleString(lang === 'fr' ? 'fr-CA' : 'en-US');

/** t('too_heavy', { mass: 12, lift: 9 }) */
export function t(key, vars = {}) {
  const s = TEXT[lang][key] ?? TEXT.fr[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
